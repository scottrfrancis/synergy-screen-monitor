#!/bin/zsh

# Synergy Screen Monitor - Watchdog Installation Script
# Installs the watchdog as a launchd user agent that starts at login and
# restarts waldo.py / found-him.py when they die.
#
# Why this copies files instead of running them in place: macOS TCC refuses
# launchd-spawned processes read access to /Volumes/workspace (an SMB mount),
# so an agent pointed at the repo fails on every spawn. The runtime is copied
# into the home directory and the plist points there. That also removes the
# boot-ordering dependency on the volume being mounted.
#
# Idempotent. start-all.sh runs it every time, so the copy tracks the repo.

set -e

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
cd "$SCRIPT_DIR"
source ./common.sh

LABEL="com.synergy.watchdog"

echo "=== Synergy Watchdog Installation ==="
echo ""

if [ "$(id -u)" = "0" ]; then
    echo "ERROR: Do not run this script as root/sudo"
    echo "The watchdog should run as your user account"
    exit 1
fi

if [ ! -f ".env" ]; then
    echo "ERROR: .env not found in $SCRIPT_DIR"
    echo "The watchdog needs ROLE, MQTT_BROKER and SYNERGY_LOG_PATH. Copy .env.example to .env first."
    exit 1
fi

resolve_real_home
resolve_python
echo "✓ $PYTHON has paho-mqtt"

INSTALL_DIR="$REALHOME/.local/share/synergy-monitor"
LAUNCHD_DIR="$REALHOME/Library/LaunchAgents"
PLIST_DEST="$LAUNCHD_DIR/$LABEL.plist"
LOG_DIR="$INSTALL_DIR/logs"   # .env says ./logs; the watchdog cd's to INSTALL_DIR

RUNTIME_FILES=(watchdog.sh start.sh stop.sh common.sh waldo.py found-him.py config.py utils.py .env)

echo "Installing runtime to $INSTALL_DIR ..."
mkdir -p "$INSTALL_DIR" "$LOG_DIR" "$LAUNCHD_DIR"
for f in "${RUNTIME_FILES[@]}"; do
    cp "$SCRIPT_DIR/$f" "$INSTALL_DIR/"
done
rm -rf "$INSTALL_DIR/mqtt_clients"
cp -R "$SCRIPT_DIR/mqtt_clients" "$INSTALL_DIR/"
find "$INSTALL_DIR" -name '__pycache__' -type d -exec rm -rf {} + 2>/dev/null || true

echo "Verifying the installed copy parses a Synergy log line ..."
PROBE='{"ts":"2026-10-27T00:00:00.000Z","source":"core","level":"INFO","msg":"switch from \"a-00000000\" to \"probe-deadbeef\" at 0,0"}'
GOT="$(cd "$INSTALL_DIR" && echo "$PROBE" | LOG_DIR="$LOG_DIR" "$PYTHON" waldo.py --dry-run)"
if [ "$GOT" != "probe" ]; then
    echo "ERROR: installed waldo.py printed '$GOT', expected 'probe'. Not loading the agent."
    exit 1
fi
echo "✓ installed copy parses the JSONL log format"

echo "Writing $PLIST_DEST ..."
cat > "$PLIST_DEST" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>$LABEL</string>

    <!-- Generated by install-watchdog.sh. Edit that script, not this file. -->
    <key>ProgramArguments</key>
    <array>
        <string>/bin/zsh</string>
        <string>$INSTALL_DIR/watchdog.sh</string>
    </array>

    <key>WorkingDirectory</key>
    <string>$INSTALL_DIR</string>

    <key>RunAtLoad</key>
    <true/>

    <key>KeepAlive</key>
    <dict>
        <key>SuccessfulExit</key>
        <false/>
        <key>NetworkState</key>
        <true/>
    </dict>

    <key>StandardOutPath</key>
    <string>$LOG_DIR/watchdog_stdout.log</string>
    <key>StandardErrorPath</key>
    <string>$LOG_DIR/watchdog_stderr.log</string>

    <key>EnvironmentVariables</key>
    <dict>
        <key>PATH</key>
        <string>/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin</string>
        <key>PYTHON</key>
        <string>$PYTHON</string>
    </dict>

    <key>ThrottleInterval</key>
    <integer>10</integer>

    <key>ProcessType</key>
    <string>Background</string>
</dict>
</plist>
PLIST

plutil -lint "$PLIST_DEST" >/dev/null || { echo "ERROR: generated plist is malformed"; exit 1; }
echo "✓ plist valid"

echo "Loading the agent ..."
reload_launch_agent "$LABEL" "$PLIST_DEST"

sleep 5
STATUS="$(launchctl list | grep "$LABEL" || true)"
if [ -z "$STATUS" ]; then
    echo ""
    echo "✗ Agent is not registered."
    echo "  Check: cat $LOG_DIR/watchdog_stderr.log"
    exit 1
fi

EXIT_CODE="$(echo "$STATUS" | awk '{print $2}')"
PID="$(echo "$STATUS" | awk '{print $1}')"
echo ""
echo "launchctl: pid=$PID last-exit=$EXIT_CODE"

if [ "$PID" = "-" ]; then
    echo "✗ Registered but not running (last exit $EXIT_CODE)."
    echo "  Check: tail $LOG_DIR/watchdog_stderr.log"
    exit 1
fi

echo ""
echo "✓ Watchdog installed and running (pid $PID)"
echo ""
echo "  Runtime : $INSTALL_DIR   (copied off /Volumes/workspace; start-all.sh refreshes it)"
echo "  Python  : $PYTHON"
echo "  Logs    : $LOG_DIR/"
echo "  Home    : $REALHOME   (resolved, not \$HOME)"
echo ""
echo "Service will now:"
echo "  - Start automatically at login"
echo "  - Monitor service health every ${WATCHDOG_CHECK_INTERVAL:-30} seconds"
echo "  - Automatically restart failed services"
echo "  - Wait for broker recovery before restarting"
echo ""
echo "Useful commands:"
echo "  Status:   launchctl list | grep $LABEL"
echo "  Logs:     tail -f $LOG_DIR/watchdog.log"
echo "  Restart:  launchctl kickstart -k gui/\$(id -u)/$LABEL"
echo "  Remove:   ./uninstall-watchdog.sh"
